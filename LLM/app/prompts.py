_UNDOCUMENTED = [c for c in TOPIC_CATEGORIES if f"- {c}:" not in _CATEGORY_GUIDE]
if _UNDOCUMENTED:
    raise RuntimeError(f"prompts.py 에 설명이 없는 카테고리: {_UNDOCUMENTED}")


def build_topic_input(message: str, source_files: Sequence[str] = ()) -> str:
    parts = [f"질문: {message}"]
    if source_files:
        # 문서명은 참고 힌트일 뿐이라는 점을 명시한다.
        parts.append("참고로 검색된 문서: " + ", ".join(source_files) + " (힌트일 뿐, 질문 의도를 우선하세요)")
    return "\n".join(parts)


