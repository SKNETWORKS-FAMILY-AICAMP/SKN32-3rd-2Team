# 상수 이름 → 그 값을 실제로 쓰는 모듈 경로.
# `from ... import X` 는 값을 복사하므로 원본이 아니라 소비처를 갈아끼워야 한다.
_CONSUMERS = {
    "TOPIC_SYSTEM": "app.services.topic",
    "ANSWER_SYSTEM": "app.services.answer",
    "CHATROOM_NAME_SYSTEM": "app.services.naming",
}


def apply(name: str) -> dict[str, str]:
    """변형을 적용하고, 실제로 바뀐 항목을 돌려준다."""
    if name not in VARIANTS:
        raise SystemExit(f"모르는 변형 '{name}'. 가능한 값: {', '.join(VARIANTS)}")

    import importlib

    overrides = VARIANTS[name]
    for const, module_path in _CONSUMERS.items():
        if const not in overrides:
            continue
        module = importlib.import_module(module_path)
        if not hasattr(module, const):
            raise SystemExit(
                f"{module_path} 에 {const} 이 없습니다. "
                "임포트 방식이 바뀌었는지 확인하세요."
            )
        setattr(module, const, overrides[const])
    return overrides


def check_categories() -> None:
    """각 후보가 카테고리 8종을 빠짐없이 설명하는지 확인한다.

    `domain.py` 에서 카테고리를 늘렸는데 후보 문안을 안 늘리면, 모델은 그
    카테고리를 영영 못 고르면서도 오류는 안 난다. 조용히 틀리는 쪽이 위험하다.
    (운영 프롬프트에는 `app/prompts.py` 가 같은 검사를 따로 갖고 있다.
     v0 은 카테고리를 이름만 나열하므로 이 검사 대상이 아니다.)
    """
    for name, text in (("catdef", _CATEGORY_DEFINITIONS), ("catdef2", _CATEGORY_DEFINITIONS_V2)):
        missing = [c for c in TOPIC_CATEGORIES if f"- {c}:" not in text]
        if missing:
            raise SystemExit(f"variants.py 의 {name} 에 설명이 없는 카테고리: {missing}")
